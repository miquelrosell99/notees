#!/usr/bin/env node
/**
 * Generate src/word/embedded.generated.ts: the Word add-in dist (plus the
 * raw manifest template) as a path -> asset map, embedded into the
 * single-file release bundle so an installed `notees word serve` needs no
 * on-disk add-in build. Text assets are JSON-escaped utf8 strings; binary
 * assets (png/ico) are base64. Re-run by the build/typecheck/test/dev
 * scripts — the output is gitignored and must never be edited by hand.
 *
 * The statics come from the in-tree add-in (scripts/word-dist-source.mjs):
 * a built clients/word checkout wins; otherwise the committed
 * word-snapshot/.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { resolveWordDistSource } from "./word-dist-source.mjs";

const cliRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolveWordDistSource(cliRoot);
if (source === undefined) {
  console.error(
    "gen-word-embedded: no Word add-in statics — build the add-in (cd clients/word && pnpm build:localhost) " +
      "or restore the committed word-snapshot/",
  );
  process.exit(1);
}
const distDir = join(source, "dist");
const templatePath = join(source, "manifest.xml");
const outputPath = join(cliRoot, "src", "word", "embedded.generated.ts");

const BINARY_EXTENSIONS = new Set([".png", ".ico"]);

function listFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full));
    else if (entry.isFile()) out.push(full);
  }
  return out;
}

if (statSync(distDir, { throwIfNoEntry: false }) === undefined) {
  console.error(`gen-word-embedded: ${distDir} is missing — the Word add-in build is incomplete; rebuild it`);
  process.exit(1);
}

const files = listFiles(distDir).filter((file) => relative(distDir, file) !== "manifest.xml");
if (files.length === 0) {
  console.error(`gen-word-embedded: ${distDir} is empty — the Word add-in build is incomplete; rebuild it`);
  process.exit(1);
}

const lines = [
  `// GENERATED by scripts/gen-word-embedded.mjs from ${source} — do not edit.`,
  "// Gitignored on purpose: the build/typecheck/test/dev scripts regenerate it,",
  "// so a bundle can never embed a stale snapshot.",
  'import type { EmbeddedWordAsset } from "./serve.js";',
  "",
  "export const EMBEDDED_WORD_ASSETS: Record<string, EmbeddedWordAsset> = {",
];
for (const file of files) {
  const webPath = `/${relative(distDir, file).split("\\").join("/")}`;
  const binary = BINARY_EXTENSIONS.has(file.slice(file.lastIndexOf(".")).toLowerCase());
  const content = binary ? readFileSync(file).toString("base64") : readFileSync(file, "utf8");
  lines.push(`  ${JSON.stringify(webPath)}: {`);
  lines.push(`    content: ${JSON.stringify(content)},`);
  lines.push(`    encoding: ${JSON.stringify(binary ? "base64" : "utf8")},`);
  lines.push(`  },`);
}
lines.push("};", "");
lines.push(
  `export const EMBEDDED_WORD_MANIFEST_TEMPLATE: string = ${JSON.stringify(readFileSync(templatePath, "utf8"))};`,
  "",
);
const output = lines.join("\n");

// Write only on change so repeat runs leave mtimes (and rebuilds) alone.
let current = null;
try {
  current = readFileSync(outputPath, "utf8");
} catch {
  current = null;
}
if (current === output) {
  console.log(`gen-word-embedded: src/word/embedded.generated.ts already up to date (${files.length} assets)`);
} else {
  writeFileSync(outputPath, output);
  console.log(`gen-word-embedded: src/word/embedded.generated.ts written (${files.length} assets, ${output.length} bytes)`);
}
