describe("planWorkflowToggle — enable ordering (anchor → classes → schemas → bindings → templates)", () => {
  const plan = enablePlan();

  it("section shape: 1 anchor + 3 classes + 15 schemas + 7 bindings + the template bodies", () => {
    const byOp = (op: string) => plan.filter((s) => s.opType === op);
    expect(byOp("object.create")).toHaveLength(1 + 1 + 7 + 1 + 8); // anchor + 2 template roots + 15 body blocks
    expect(byOp("class.create")).toHaveLength(3);
    expect(byOp("propertySchema.create")).toHaveLength(15);
    expect(byOp("class.property.set")).toHaveLength(7);
    expect(byOp("property.set")).toHaveLength(3 + 2); // graft values + has-template values
    expect(plan).toHaveLength(48);
  });

  it("step 0 is the anchor tag page — an ordinary parentless page at the derived id", () => {
    expect(plan[0]).toEqual({
      opType: "object.create",
      payload: {
        objectId: derived("tag", "research"),
        parentId: null,
        contentAst: [{ type: "text", text: "Research" }],
      },
    });
  });

  it("classes come next, in spec order, active by default (no active key)", () => {
    const classes = plan.slice(1, 4);
    expect(classes.map((s) => s.opType)).toEqual(["class.create", "class.create", "class.create"]);
    expect(classes.map((s) => s.payload.classId)).toEqual([
      derived("class", "synthesis"),
      derived("class", "comparison"),
      derived("class", "source_instance"),
    ]);
    for (const step of classes) {
      expect(step.payload).not.toHaveProperty("active");
      expect(step.payload).not.toHaveProperty("parentlessRole");
      expect(step.payload).not.toHaveProperty("displayTemplate");
    }
  });

  it("schemas follow (+options), scoped per the doc vocabulary, in spec order", () => {
    const schemas = plan.slice(4, 19);
    expect(schemas.every((s) => s.opType === "propertySchema.create")).toBe(true);
    const schemaByKey = new Map(schemas.map((s) => [schemaKeyOf(s), s]));
    // status: select bound to the SYSTEM question class, scope [question].
    const status = schemaByKey.get("status")!;
    expect(status.payload).toMatchObject({
      propertySchemaId: derived("schema", "status"),
      name: "Status",
      type: "select",
      multi: false,
      scopeClassIds: [SYSTEM_CLASS_UUIDS.question],
      options: [
        { id: derived("schema", "status:stillOpen"), label: "still open" },
        { id: derived("schema", "status:partlyAddressed"), label: "partly addressed" },
        { id: derived("schema", "status:inPreparation"), label: "in preparation" },
        { id: derived("schema", "status:setAside"), label: "set aside" },
      ],
    });
    // move: select scoped + bound to the workflow synthesis class.
    const move = schemaByKey.get("move")!;
    expect(move.payload).toMatchObject({
      propertySchemaId: derived("schema", "move"),
      type: "select",
      scopeClassIds: [derived("class", "synthesis")],
    });
    // guidingInquiries: multi node-backed text scoped [project] (system class).
    const guiding = schemaByKey.get("guidingInquiries")!;
    expect(guiding.payload).toMatchObject({
      propertySchemaId: derived("schema", "guidingInquiries"),
      name: "Guiding inquiries",
      type: "text",
      multi: true,
      scopeClassIds: [SYSTEM_CLASS_UUIDS.project],
    });
    // The source-instance set: scoped [source_instance], unbound.
    for (const key of ["whyItBelongs", "readingPurpose", "whatItContributed"]) {
      const step = schemaByKey.get(key)!;
      expect(step.payload.type).toBe("text");
      expect(step.payload.multi).toBe(false);
      expect(step.payload.scopeClassIds).toEqual([derived("class", "source_instance")]);
    }
    const engagement = schemaByKey.get("engagement")!;
    expect(engagement.payload.type).toBe("select");
    expect(engagement.payload.scopeClassIds).toEqual([derived("class", "source_instance")]);
    expect((engagement.payload.options as unknown[]).map((o) => (o as { label: string }).label)).toEqual([
      "encountered",
      "engaged",
      "extracted",
      "integrated",
    ]);
    // The writing-plan set: scoped [plan], unbound (the template graft authors them).
    for (const key of ["workingPosition", "complication", "unresolved"]) {
      const step = schemaByKey.get(key)!;
      expect(step.payload.scopeClassIds).toEqual([SYSTEM_CLASS_UUIDS.plan]);
      expect(step.payload.bindTo).toBeUndefined();
    }
    // The source-definition set: scoped [source], bound, hideWhenEmpty.
    for (const key of ["objective", "method", "results", "conclusions", "limitations"]) {
      const step = schemaByKey.get(key)!;
      expect(step.payload.scopeClassIds).toEqual([SYSTEM_CLASS_UUIDS.source]);
      expect(step.payload.hideWhenEmpty).toBe(true);
    }
  });

  it("binding rows land AFTER every schema create — status→question, move→synthesis, the five→source", () => {
    const bindings = plan.slice(19, 26);
    expect(bindings.every((s) => s.opType === "class.property.set")).toBe(true);
    expect(
      bindings.map((s) => [s.payload.classId, s.payload.propertySchemaId]),
    ).toEqual([
      [SYSTEM_CLASS_UUIDS.question, derived("schema", "status")],
      [derived("class", "synthesis"), derived("schema", "move")],
      [SYSTEM_CLASS_UUIDS.source, derived("schema", "objective")],
      [SYSTEM_CLASS_UUIDS.source, derived("schema", "method")],
      [SYSTEM_CLASS_UUIDS.source, derived("schema", "results")],
      [SYSTEM_CLASS_UUIDS.source, derived("schema", "conclusions")],
      [SYSTEM_CLASS_UUIDS.source, derived("schema", "limitations")],
    ]);
    // The plan/synthesis/instance sets stay unbound — no binding step may
    // address them.
    for (const key of ["guidingInquiries", "whyItBelongs", "engagement", "workingPosition"]) {
      expect(
        bindings.some((s) => s.payload.propertySchemaId === derived("schema", key)),
      ).toBe(false);
    }
  });

  it("templates: writing-plan root (classed template + Research tag), body blocks depth-first, graft values, has-template value", () => {
    const tail = plan.slice(26);
    // Root create.
    expect(tail[0]).toEqual({
      opType: "object.create",
      payload: {
        objectId: derived("template", "writingPlan"),
        parentId: null,
        classIds: [SYSTEM_CLASS_UUIDS.template],
        tagIds: [derived("tag", "research")],
        contentAst: [{ type: "text", text: "Writing plan — {{name}}" }],
      },
    });
    // Seven body blocks, depth-first, parented correctly.
    const body = tail.slice(1, 8);
    expect(body.map((s) => s.payload.objectId)).toEqual([
      derived("template", "writingPlan/chosenMaterial"),
      derived("template", "writingPlan/chosenMaterial/chosenMaterialPlaceholder"),
      derived("template", "writingPlan/workingPositionCarrier"),
      derived("template", "writingPlan/complicationCarrier"),
      derived("template", "writingPlan/unresolvedCarrier"),
      derived("template", "writingPlan/detailedOutline"),
      derived("template", "writingPlan/detailedOutline/outlineStarter"),
    ]);
    expect(body[0]!.payload.parentId).toBe(derived("template", "writingPlan"));
    expect(body[1]!.payload.parentId).toBe(derived("template", "writingPlan/chosenMaterial"));
    // The three graft values: node-backed text ({nodeId} carrier refs) on the template.
    const grafts = tail.slice(8, 11);
    expect(grafts.map((s) => [s.payload.propertySchemaId, s.payload.value])).toEqual([
      [derived("schema", "workingPosition"), { nodeId: derived("template", "writingPlan/workingPositionCarrier") }],
      [derived("schema", "complication"), { nodeId: derived("template", "writingPlan/complicationCarrier") }],
      [derived("schema", "unresolved"), { nodeId: derived("template", "writingPlan/unresolvedCarrier") }],
    ]);
    for (const graft of grafts) {
      expect(graft.opType).toBe("property.set");
      expect(graft.payload.objectId).toBe(derived("template", "writingPlan"));
    }
    // The has-template value rides the class node (system `plan`), with the
    // deterministic OR-Set element id.
    expect(tail[11]).toEqual({
      opType: "property.set",
      payload: {
        objectId: SYSTEM_CLASS_UUIDS.plan,
        propertySchemaId: SYSTEM_PROPERTY_UUIDS.hasTemplate,
        value: { nodeId: derived("template", "writingPlan") },
        elementId: derived("template", "writingPlan:hasTemplate"),
        idx: 0,
      },
    });
  });

  it("the comparison template binds to the workflow comparison class, untagged", () => {
    const tail = plan.slice(38);
    expect(tail[0]).toEqual({
      opType: "object.create",
      payload: {
        objectId: derived("template", "comparison"),
        parentId: null,
        classIds: [SYSTEM_CLASS_UUIDS.template],
        contentAst: [{ type: "text", text: "Comparison" }],
      },
    });
    expect(tail[0]!.payload).not.toHaveProperty("tagIds");
    expect(tail[tail.length - 1]).toEqual({
      opType: "property.set",
      payload: {
        objectId: derived("class", "comparison"),
        propertySchemaId: SYSTEM_PROPERTY_UUIDS.hasTemplate,
        value: { nodeId: derived("template", "comparison") },
        elementId: derived("template", "comparison:hasTemplate"),
        idx: 0,
      },
    });
  });

  it("the plan is pure — two calls return deep-equal results", () => {
    expect(enablePlan()).toEqual(enablePlan());
  });

  it("every step's payload validates against the protocol op schema (wire-legal plan)", () => {
    for (const step of plan) {
      const schema = payloadSchemaFor(step.opType);
      expect(schema, step.opType).toBeDefined();
      const parsed = schema!.safeParse(step.payload);
      expect(parsed.success, JSON.stringify(parsed.success ? {} : parsed.error.issues)).toBe(true);
    }
  });
});

describe("planWorkflowToggle — disable (archive exactly the classes + templates, nothing else)", () => {
  it("five object.update {active:false} steps — the 3 workflow classes, then the 2 templates", () => {
    const plan = disablePlan();
    expect(plan).toHaveLength(5);
    expect(plan.every((s) => s.opType === "object.update")).toBe(true);
    expect(plan.map((s) => [s.payload.objectId, s.payload.active])).toEqual([
      [derived("class", "synthesis"), false],
      [derived("class", "comparison"), false],
      [derived("class", "source_instance"), false],
      [derived("template", "writingPlan"), false],
      [derived("template", "comparison"), false],
    ]);
    // Never the anchor, never the schemas, never a system class.
    const touched = new Set(plan.map((s) => s.payload.objectId as string));
    expect(touched.has(derived("tag", "research"))).toBe(false);
    expect(touched.has(SYSTEM_CLASS_UUIDS.question)).toBe(false);
    expect(touched.has(SYSTEM_CLASS_UUIDS.plan)).toBe(false);
    expect(touched.has(SYSTEM_CLASS_UUIDS.source)).toBe(false);
    expect(touched.has(derived("schema", "status"))).toBe(false);
  });

  it("every disable step's payload validates against the protocol op schema", () => {
    for (const step of disablePlan()) {
      const parsed = payloadSchemaFor(step.opType)!.safeParse(step.payload);
      expect(parsed.success).toBe(true);
    }
  });
});

/** Reads a schema step's registry key back off its deterministic id
 *  (option ids carry a second colon; schema ids exactly one). */
function schemaKeyOf(step: WorkflowOpStep): string {
  const id = step.payload.propertySchemaId as string;
  const hit = Object.entries(DERIVED_IDS).find(
    ([qualified, value]) =>
      qualified.startsWith("schema:") &&
      value === id &&
      qualified.slice("schema:".length).includes(":") === false,
  );
  expect(hit, id).toBeTruthy();
  return hit![0].slice("schema:".length);
}
