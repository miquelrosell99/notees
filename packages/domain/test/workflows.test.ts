function derived(kind: string, key: string): string {
  return DERIVED_IDS[`${kind}:${key}` as keyof typeof DERIVED_IDS];
}

const enablePlan = (): WorkflowOpStep[] => planWorkflowToggle("research", "enabled");
const disablePlan = (): WorkflowOpStep[] => planWorkflowToggle("research", "disabled");

describe("workflow identity (D1 deterministic ids)", () => {
  it("pins the exact format string — web and CLI derive from this contract forever", () => {
    // The format is the contract: <workflowId>:<kind>:<key> under the
    // notees:workflow namespace (SCHEMA.md "Starter vocabulary" ruling).
    expect(workflowEntityId("research", "class", "synthesis")).toBe(
      deriveUuid("notees:workflow:research:class:synthesis"),
    );
    expect(workflowEntityId("research", "schema", "status:stillOpen")).toBe(
      deriveUuid("notees:workflow:research:schema:status:stillOpen"),
    );
  });

  it("snapshot: every materializable entity id is pinned verbatim", () => {
    for (const [qualified, id] of Object.entries(DERIVED_IDS)) {
      const sep = qualified.indexOf(":");
      const kind = qualified.slice(0, sep) as "tag" | "class" | "schema" | "template";
      const key = qualified.slice(sep + 1);
      expect(workflowEntityId("research", kind, key), qualified).toBe(id);
    }
  });

  it("the anchor id derives from the anchor spec's tag key", () => {
    expect(WORKFLOWS.research.anchor).toEqual({ kind: "tag", key: "research", title: "Research" });
    expect(workflowAnchorId("research")).toBe(derived("tag", "research"));
  });

  it("deriveUuid is byte-stable with the former server implementation", () => {
    // The actor-id namespace must never drift (live relay rows derive from
    // it) — pins the sha256/uuid5 algorithm, not just the workflow namespace.
    expect(deriveUuid("notees:actor:test")).toBe("a99c0f45-6eec-55f5-94fb-ee9ed70e42bf");
  });
});

